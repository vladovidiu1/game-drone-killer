"""Validate configurable M1 simulation targets and render honest before/after tables."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
base=json.loads((root/'docs/m1/baseline.json').read_text())
final=json.loads((root/'docs/m1/after.json').read_text())
config=json.loads((root/'data/definitions.json').read_text())
lookup={(r['id'],r['strategy']):r for r in final['rows']}
assert base['failures']==final['failures']==0
assert len(base['rows'])==len(final['rows'])==55
for left,right in zip(base['rows'],final['rows']):
 assert (left['id'],left['strategy'],left['seed'],left['research_tier'])==(right['id'],right['strategy'],right['seed'],right['research_tier'])
 assert right['finished']
for key,target in config['balance']['targets'].items():
 row=lookup[(int(key),'hybrid')]
 assert row['victory'] and row['health']>=target['hybrid_min_health']
 assert row['manual_hits']>=target['hybrid_min_manual_hits']
 if int(key)>=5:
  assert not lookup[(int(key),'automatic')]['victory']
for strategy in ['two_mg','two_cannon','two_mixed']:
 assert not all(r['victory'] for r in final['rows'] if r['strategy']==strategy)
for r in final['rows']:
 if r['strategy'].startswith('two_'):assert r['turrets']<=2 and r['manual_shots']==0
lines=['# M1 comparison tables','','Generated by `python tools/report_m1_balance.py`. These are fixed-policy simulations, not human difficulty scores. See [method and limitations](../M1_BALANCE.md).','','## Fixed two-turret policy, all territories','','Ordinary budgets and bounty-funded upgrades; no abilities, no primary fire, slots 3 and 4 (zero-based 2/3). MG + Cannon. This samples one placement, not an exhaustive search.','','| Mission | G6 win / HP | M1 win / HP | G6 → M1 breaches | G6 → M1 peak concurrency |','| --- | --- | --- | --- | --- |']
old={(r['id'],r['strategy']):r for r in base['rows']}
for id in range(1,26):
 a=old[id,'two_mixed'];b=lookup[id,'two_mixed']
 lines.append(f"| {id:02d} | {'Win' if a['victory'] else 'Loss'} / {a['health']} | {'Win' if b['victory'] else 'Loss'} / {b['health']} | {a['breaches']} → {b['breaches']} | {a['peak_enemies']} → {b['peak_enemies']} |")
lines+=['','## Chapter milestones','','Research level is the fixture tier (0 / 1 / 2 / 3 / 4 / 5), not earned campaign progression. Full automatic and manual-only cases may repair using BC; the hybrid policy does too. Boss core armor and overload remain unchanged from G6.','','| Mission | Mode | G6 win / HP | M1 win / HP | G6 → M1 primary hits | G6 → M1 elapsed sim seconds |','| --- | --- | --- | --- | --- | --- |']
for b in final['rows']:
 if b['id'] not in [1,5,10,15,20,25]:continue
 a=old[b['id'],b['strategy']]
 lines.append(f"| {b['id']:02d} | {b['strategy']} | {'Win' if a['victory'] else 'Loss'} / {a['health']} | {'Win' if b['victory'] else 'Loss'} / {b['health']} | {a['manual_hits']} → {b['manual_hits']} | {a['seconds']} → {b['seconds']} |")
(root/'docs/m1/COMPARISON.md').write_text('\n'.join(lines)+'\n')
print('M1 targets pass: 55 completed cases; 6 hybrid milestones meet configured HP/hit goals; late automatic-only cases lose; no two-turret policy is universal')
